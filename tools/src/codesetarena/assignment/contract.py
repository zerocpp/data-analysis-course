class AssignmentError(RuntimeError):
    """Assignment Pipeline 结构化错误：携带稳定 error_code（§88）。"""

    def __init__(self, code: str, message: str):
        super().__init__(f"{code}: {message}")
        self.code = code
        self.message = message


def assignment_error(code: str, message: str) -> AssignmentError:
    return AssignmentError(code, message)


